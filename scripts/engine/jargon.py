def scan(text):
    """掃描一段文本，回報 L1 黑話 / L2 框架詞命中。

    返回 dict：
        l1_hits   {詞: 次數}  ← 必須為空才算過關
        l2_hits   {詞: 次數}  ← 僅統計（框架詞保留專業感）
        l1_total / l2_total   總命中數
    """
    t = text or ""
    for a in JARGON_ALLOW:          # 客戶自有術語先屏蔽，避免誤判
        t = t.replace(a, "\u3000")
    l1 = {w: t.count(w) for w in JARGON_L1 if w in t}
    l2 = {w: t.count(w) for w in JARGON_L2 if w in t}
    return {
        "l1_hits": l1,
        "l2_hits": l2,
        "l1_total": sum(l1.values()),
        "l2_total": sum(l2.values()),
    }


def humanize(text):
    """把一段文本按 L1 字典換成白話（僅做保險用；優先在源碼層改寫）。"""
    out = text or ""
    # 白名單先佔位，替換完再還原，確保客戶術語原樣保留
    holds = {}
    for i, a in enumerate(JARGON_ALLOW):
        if a in out:
            ph = f"\x00{i}\x00"
            holds[ph] = a
            out = out.replace(a, ph)
    # 長詞優先，避免「基线跑测」被「基线」先切走
    for w in sorted(JARGON_L1, key=len, reverse=True):
        if w in out:
            out = out.replace(w, JARGON_L1[w])
    for ph, a in holds.items():
        out = out.replace(ph, a)
    return out


