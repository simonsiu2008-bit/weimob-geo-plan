"""術語白話化字典與掃描器（plain-language guard）

由來
----
客戶反饋：「還是在用基准线什麼的國內術語，減少術語的表達，讓方案診斷看起來更深入淺出
一點」。根因是 `references/plain_language.md` 只是一份**建議**，沒有任何機制強制落地，
引擎固定文案照樣用黑話。本模組把它變成**可掃描的硬規則**，供 QA 執行。

兩級分類
--------
- **L1 黑話（必換）**：內地互聯網黑話，客戶老闆看着不自然、運營接不住。
  QA 對交付物掃描，命中數**必須為 0**。
- **L2 框架詞（首配白話）**：GEO 產品核心概念，全刪會失專業感；要求
  **首次出現時配一句人話**（見 `references/plain_language.md` 對照表）。
  QA 只統計、不判失敗（避免誤傷必要概念）。

用法
----
    from jargon import scan, JARGON_L1, JARGON_L2
    r = scan(open("產物.txt", encoding="utf-8").read())
    r["l1_hits"]   # {"基线": 3, ...}  ← 必須為空
    r["l2_hits"]   # {"AIVO": 4, ...}  ← 僅統計
"""

