def _norm(style, table):
    if style in table:
        return style
    raise KeyError(f"[lang_style] 未知语言风格 '{style}'，可选: {list(table)}")


def resolve_styles(source):
    """从 case 配置解析要并行输出的视觉版本列表。
    source: config dict 或模块对象。查找顺序：
      dict    → source["VISUAL_STYLES"]
      module  → 模块级 VISUAL_STYLES 属性，其次 source.CONFIG / source.TOPIC_CONFIG dict 内的键
    默认 ["classic"]（历史行为完全不变）。
    """
    styles = None
    if isinstance(source, dict):
        styles = source.get("VISUAL_STYLES")
    else:
        styles = getattr(source, "VISUAL_STYLES", None)
        if not styles:
            for attr in ("CONFIG", "TOPIC_CONFIG"):
                cfg = getattr(source, attr, None)
                if isinstance(cfg, dict) and cfg.get("VISUAL_STYLES"):
                    styles = cfg["VISUAL_STYLES"]
                    break
    if not styles:
        styles = ["classic"]
    if isinstance(styles, str):
        styles = [styles]
    for s in styles:
        if s not in STYLE_SUFFIX:
            raise KeyError(f"[lang_style] 未知视觉版本 '{s}'，可选: {list(STYLE_SUFFIX)}")
    return list(styles)


def style_suffix(style):
    return STYLE_SUFFIX.get(style, f"_{style}")


def versioned_filename(out_filename, style):
    """classic → 原文件名（原版本保留）；其他风格 → 文件名加版本后缀。"""
    stem, ext = os.path.splitext(out_filename)
    return f"{stem}{style_suffix(style)}{ext}"
